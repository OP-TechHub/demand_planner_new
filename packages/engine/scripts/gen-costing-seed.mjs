// Generate the costing seed migration from the committed v11 fixture.
//
// Generated rather than hand-written: 34 SKUs x 12 numeric columns is exactly
// the kind of transcription that goes wrong silently, and the fixture is
// already the workbook's own values, asserted by the parity suite.
//
// Run from repo root:  node packages/engine/scripts/gen-costing-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const v11 = JSON.parse(readFileSync('packages/engine/fixtures/v11.json', 'utf8'));
const OUT = 'supabase/migrations/20260824000002_costing_seed.sql';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const n = (x) => (x === null || x === undefined ? 'null' : String(x));

// Bucket bounds come from the label; medians and FCR from the workbook.
const bounds = (label) => {
  const m = label.match(/^(\d+)-(\d+)g$/);
  if (!m) throw new Error(`cannot parse bucket label: ${label}`);
  return { minG: Number(m[1]), maxG: Number(m[2]) };
};

// Decisions §7: the by-product rows absorb their raw material; everything else,
// co-products included, stays full_fish and reproduces v11 exactly.
const basisFor = (sku) => (sku.category === 'By-product' ? 'absorbed' : 'full_fish');

const L = [];
const w = (s = '') => L.push(s);

w('-- ============================================================================');
w('-- Costing module — seed from barramundi_costing_v11.xlsx');
w('--');
w('-- GENERATED by packages/engine/scripts/gen-costing-seed.mjs from the committed');
w('-- fixture packages/engine/fixtures/v11.json. Do not hand-edit: regenerate.');
w('--');
w('-- Values are the workbook\'s own, and the engine reproduces them to a relative');
w('-- 1e-9 (packages/engine/test/costing-parity.test.ts). Two things here are');
w('-- deliberately NOT the workbook:');
w('--   1. The six by-product SKUs ship as raw_material_basis = absorbed');
w('--      (Decisions §7). The other 28 are full_fish and match v11 exactly.');
w('--   2. Per-bucket FCR is the workbook\'s PLACEHOLDER (v11 flags it as such at');
w('--      cell A22), and per-bucket yields are seeded from each SKU\'s flat yield.');
w('--      Both are editable and get real farm data later (Decisions §6).');
w('-- ============================================================================');
w('');
w('set search_path = demand_planner, public;');
w('');
w('-- ---------------------------------------------------------------------------');
w('-- 1. Size buckets — costing\'s own copy (Decisions §6)');
w('-- ---------------------------------------------------------------------------');
w('insert into demand_planner.cost_size_buckets (org_id, label, min_g, max_g, median_g, fcr, sort_order)');
w('select o.id, b.label, b.min_g, b.max_g, b.median_g, b.fcr, b.sort_order');
w('from demand_planner.organizations o,');
w('     (values');
w(
  v11.buckets
    .map((b, i) => {
      const { minG, maxG } = bounds(b.label);
      return `        (${q(b.label)}, ${minG}, ${maxG}, ${b.medianG}, ${b.fcr}::numeric, ${(i + 1) * 10})`;
    })
    .join(',\n')
);
w('     ) as b(label, min_g, max_g, median_g, fcr, sort_order)');
w("where o.slug = 'oceanpick'");
w('on conflict (org_id, label) do nothing;');
w('');

w('-- ---------------------------------------------------------------------------');
w('-- 2. Destinations — the port list (rates land on the version, below)');
w('-- ---------------------------------------------------------------------------');
w('insert into demand_planner.cost_destinations (org_id, name, sort_order)');
w('select o.id, d.name, d.sort_order');
w('from demand_planner.organizations o,');
w('     (values');
w(v11.destinations.map((d, i) => `        (${q(d.name)}, ${(i + 1) * 10})`).join(',\n'));
w('     ) as d(name, sort_order)');
w("where o.slug = 'oceanpick'");
w('on conflict (org_id, name) do nothing;');
w('');

const a = v11.assumptions;
w('-- ---------------------------------------------------------------------------');
w('-- 3. Assumption version 1 — the workbook as at v11 (Decisions §4)');
w('-- ---------------------------------------------------------------------------');
w('insert into demand_planner.cost_assumption_versions (');
w('  org_id, version_no, label, notes, is_current,');
w('  feed_cost_per_kg, clearing_cost_per_kg, fcr_reference, fx_rate,');
w('  import_tax_pct_domestic, import_tax_pct_export,');
w('  domestic_transport_lkr, domestic_cold_hold_lkr,');
w('  export_freight_to_port_usd, export_cold_chain_usd,');
w('  rack_margin_pct, fob_margin_pct,');
w('  importer_clearing_pct, importer_markup_pct, distributor_markup_pct,');
w('  container_fill_kg, air_lot_kg');
w(')');
w('select');
w(`  o.id, 1, 'v11 (imported)', 'Imported from barramundi_costing_v11.xlsx', true,`);
w(`  ${n(a.feedCostPerKg)}, ${n(a.clearingCostPerKg)}, ${n(a.fcrReference)}, ${n(a.fxRate)},`);
w(`  ${n(a.importTaxPct.domestic)}, ${n(a.importTaxPct.export)},`);
w(`  ${n(a.domestic.transportLkr)}, ${n(a.domestic.coldHoldLkr)},`);
w(`  ${n(a.export.freightToPortUsd)}, ${n(a.export.coldChainUsd)},`);
w(`  ${n(a.margins.rackPct)}, ${n(a.margins.fobPct)},`);
w(`  ${n(a.margins.importerClearingPct)}, ${n(a.margins.importerMarkupPct)}, ${n(a.margins.distributorMarkupPct)},`);
w(`  ${n(a.freight.containerFillKg)}, ${n(a.freight.airLotKg)}`);
w('from demand_planner.organizations o');
w("where o.slug = 'oceanpick'");
w('on conflict (org_id, version_no) do nothing;');
w('');

w('-- ---------------------------------------------------------------------------');
w('-- 4. ODC components (Decisions §3 / handoff §3.2)');
w('--');
w('-- basis drives size-bucket amortisation: per_fish divides by the median');
w('-- weight, per_kg stays flat. v11 hard-codes this; here it is editable.');
w('-- ---------------------------------------------------------------------------');
w('insert into demand_planner.cost_odc_components (version_id, name, value, currency, basis, sort_order)');
w('select v.id, c.name, c.value, c.currency::demand_planner.cost_currency, c.basis::demand_planner.cost_odc_basis, c.sort_order');
w('from demand_planner.cost_assumption_versions v');
w('join demand_planner.organizations o on o.id = v.org_id');
w('cross join (values');
w(
  a.odc
    .map((c, i) => `        (${q(c.name)}, ${c.value}::numeric, ${q(c.currency)}, ${q(c.basis)}, ${(i + 1) * 10})`)
    .join(',\n')
);
w('     ) as c(name, value, currency, basis, sort_order)');
w("where o.slug = 'oceanpick' and v.version_no = 1");
w('on conflict (version_id, name) do nothing;');
w('');

w('-- ---------------------------------------------------------------------------');
w('-- 5. Destination rates for version 1');
w('--');
w('-- Per shipment, not per kg: the engine divides by container_fill_kg /');
w('-- air_lot_kg so changing the fill weight reprices every port at once.');
w('-- ---------------------------------------------------------------------------');
w('insert into demand_planner.cost_destination_rates (version_id, destination_id, sea_rate_per_20ft, air_rate_per_lot)');
w('select v.id, d.id, r.sea, r.air');
w('from demand_planner.cost_assumption_versions v');
w('join demand_planner.organizations o on o.id = v.org_id');
w('join (values');
w(
  v11.destinations
    .map((d) => `        (${q(d.name)}, ${d.seaRatePer20ft}::numeric, ${d.airRatePerLot}::numeric)`)
    .join(',\n')
);
w('     ) as r(name, sea, air) on true');
w('join demand_planner.cost_destinations d on d.org_id = o.id and d.name = r.name');
w("where o.slug = 'oceanpick' and v.version_no = 1");
w('on conflict (version_id, destination_id) do nothing;');
w('');

w('-- ---------------------------------------------------------------------------');
w('-- 6. SKU master — one list, both markets (Decisions §2)');
w('--');
w('-- process/packing/marinade are USD everywhere; domestic converts at FX.');
w('-- glaze_pct is 0 on every v11 row: glaze is a per-SKU input that drives the');
w('-- "with glaze" output block, not a reason to duplicate a SKU.');
w('-- ---------------------------------------------------------------------------');
w('insert into demand_planner.cost_skus (');
w('  org_id, name, status, category, sort_order, glaze_pct, base_yield,');
w('  pct_fish, pct_marinade, marinade_usd_per_kg, process_usd_per_kg,');
w('  packing_usd_per_kg, pack_size, raw_material_basis');
w(')');
w('select o.id, s.name, s.status::demand_planner.cost_sku_status, s.category, s.sort_order,');
w('       s.glaze_pct, s.base_yield, s.pct_fish, s.pct_marinade,');
w('       s.marinade_usd, s.process_usd, s.packing_usd, s.pack_size,');
w('       s.basis::demand_planner.cost_raw_material_basis');
w('from demand_planner.organizations o,');
w('     (values');
w(
  v11.skus
    .map(
      (s, i) =>
        `        (${q(s.name)}, ${q(s.status)}, ${q(s.category)}, ${(i + 1) * 10}, ` +
        `${s.glazePct}::numeric, ${s.baseYield}::numeric, ${s.pctFish}::numeric, ${s.pctMarinade}::numeric, ` +
        `${s.marinadeUsdPerKg}::numeric, ${s.processUsdPerKg}::numeric, ${s.packingUsdPerKg}::numeric, ` +
        `${s.packSize === null ? 'null::text' : q(s.packSize)}, ${q(basisFor(s))})`
    )
    .join(',\n')
);
w('     ) as s(name, status, category, sort_order, glaze_pct, base_yield,');
w('            pct_fish, pct_marinade, marinade_usd, process_usd, packing_usd,');
w('            pack_size, basis)');
w("where o.slug = 'oceanpick'");
w('on conflict do nothing;');
w('');

w('-- ---------------------------------------------------------------------------');
w('-- 7. Per-bucket yields — PLACEHOLDERS (Decisions §6)');
w('--');
w('-- Every bucket starts at the SKU\'s flat yield, so the table is usable from');
w('-- day one and obviously still needs real data: while every bucket holds the');
w('-- same number, switching buckets on changes only FCR and ODC, never yield.');
w('-- Replace with the farm\'s yield at each bucket median.');
w('-- ---------------------------------------------------------------------------');
w('insert into demand_planner.cost_sku_bucket_yields (sku_id, bucket_id, yield_pct)');
w('select s.id, b.id, s.base_yield');
w('from demand_planner.cost_skus s');
w('join demand_planner.cost_size_buckets b on b.org_id = s.org_id');
w('on conflict (sku_id, bucket_id) do nothing;');
w('');

const byProducts = v11.skus.filter((s) => basisFor(s) === 'absorbed').map((s) => s.name);
w('-- ---------------------------------------------------------------------------');
w('-- 8. Sanity check');
w('-- ---------------------------------------------------------------------------');
w('do $$');
w('declare');
w('  n_skus int;');
w('  n_absorbed int;');
w('begin');
// Scoped to the org, not a bare count: a second org's SKUs must not make this
// pass or fail by accident.
w('  select count(*) into n_skus');
w('    from demand_planner.cost_skus s');
w('    join demand_planner.organizations o on o.id = s.org_id');
w("   where o.slug = 'oceanpick';");
w('  select count(*) into n_absorbed');
w('    from demand_planner.cost_skus s');
w('    join demand_planner.organizations o on o.id = s.org_id');
w("   where o.slug = 'oceanpick' and s.raw_material_basis = 'absorbed';");
w(`  if n_skus <> ${v11.skus.length} then`);
w(`    raise exception 'expected ${v11.skus.length} costing SKUs, found %', n_skus;`);
w('  end if;');
w(`  if n_absorbed <> ${byProducts.length} then`);
w(`    raise exception 'expected ${byProducts.length} absorbed by-product SKUs, found %', n_absorbed;`);
w('  end if;');
w('end $$;');
w('');

writeFileSync(OUT, L.join('\n'));
console.log(
  `${OUT}: ${v11.buckets.length} buckets, ${v11.destinations.length} destinations, ` +
    `${a.odc.length} ODC components, ${v11.skus.length} SKUs (${byProducts.length} absorbed: ${byProducts.join(', ')})`
);
